Vec3 simulation::calculate_linear_momentum() {
    Vec3 momentum_times_g{};

    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;

        momentum_times_g += celestial_bodies.velocity(i) * celestial_bodies.gravitational_masses[i];
    }

    return momentum_times_g / config::GRAVITATIONAL_CONSTANT;
}

double simulation::calculate_kinetic_energy() {
    // Definitions:
    // µ_i = G * m_i

    // Kinetic energy:
    // K = sum_i 1/2 * m_i * |v_i|^2
    //   = 1/2 sum_i µ_i / G * |v_i|^2
    //   = 1/(2 * G) sum_i µ_i * |v_i|^2
    //   = 1/(2 * G) sum_i µ_i * (v_i dot v_i)
    // These formations improve the performance, because instead of diving by 2*G for every body, we only compute it once.

    double kinetic_energy_times_2g = 0;

    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;

        kinetic_energy_times_2g += celestial_bodies.gravitational_masses[i] * celestial_bodies.velocity(i).dot(celestial_bodies.velocity(i));
    }

    return kinetic_energy_times_2g / (config::GRAVITATIONAL_CONSTANT * 2);
}

double simulation::calculate_total_energy() {
    const double kinetic_energy = calculate_kinetic_energy();

    // Definitions:
    // µ_i = G * m_i
    // r = |r_j - r_i|, n = (r_j - r_i) / r
    // R_i = equatorial radius, k_i = unit pole axis
    // u_i = n dot k_i, P2(u) = (3*u^2 - 1) / 2

    // Newtonian potential energy:
    // U_N = -sum_(active pairs i < j) G*m_i*m_j / r
    //     = -(1/G) * sum_(active pairs i < j) µ_i*µ_j / r

    // J2 potential energy correction:
    // U_J2 = sum_(active pairs i < j)
    //          G*m_i*m_j / r^3
    //          * [J2_i*R_i^2*P2(u_i) + J2_j*R_j^2*P2(u_j)]
    //      = (1/G) * sum_(active pairs i < j)
    //          µ_i*µ_j / r
    //          * [J2_i*(R_i/r)^2*P2(u_i) + J2_j*(R_j/r)^2*P2(u_j)]

    // Combined potential energy:
    // U = (1/G) * sum_(active pairs i < j)
    //               µ_i*µ_j / r
    //               * [-1 + J2_i*(R_i/r)^2*P2(u_i) + J2_j*(R_j/r)^2*P2(u_j)]

    double potential_energy_times_g = 0;

    for (const auto& [i, j] : force_pairs::active_pairs) {
        const Vec3 separation = celestial_bodies.position(i) - celestial_bodies.position(j);
        const double distance = separation.length();

        double j2_correction = 0.0;

        if (runtime_config::use_j2) {
            const Vec3 direction = separation / distance;

            for (const std::size_t source : {i, j}) {
                if (celestial_bodies.j2[source] == 0.0 || celestial_bodies.gravitational_masses[source] == 0.0) {
                    continue;
                }

                const double u = direction.dot(celestial_bodies.pole_axes[source]);
                const double p2 = 0.5 * (3.0 * u * u - 1.0);
                const double radius_ratio = celestial_bodies.equatorial_radii[source] / distance;

                j2_correction += celestial_bodies.j2[source] * radius_ratio * radius_ratio * p2;
            }
        }

        potential_energy_times_g += celestial_bodies.gravitational_masses[i] * celestial_bodies.gravitational_masses[j] / distance * (-1.0 + j2_correction);
    }

    const double potential_energy = potential_energy_times_g / config::GRAVITATIONAL_CONSTANT;

    return kinetic_energy + potential_energy;
}

double simulation::calculate_total_mass() {
    double total_gravitation_masses = 0;

    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;

        total_gravitation_masses += celestial_bodies.gravitational_masses[i];
    }

    return total_gravitation_masses / config::GRAVITATIONAL_CONSTANT;
}

Vec3 simulation::calculate_barycenter(const double total_mass) {
    // Barycenter:
    // R = (sum_i m_i * r_i) / (sum_i m_i)
    //   = (sum_i µ_i / G * r_i) / (sum_i m_i * G / G)
    //   = (sum_i µ_i * r_i) / (sum_i m_i * G)

    Vec3 weighted_positions{};

    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;

        weighted_positions += celestial_bodies.position(i) * celestial_bodies.gravitational_masses[i];
    }

    return weighted_positions / (total_mass * config::GRAVITATIONAL_CONSTANT);
}

Vec3 simulation::calculate_expected_barycenter(const Vec3& baseline_barycenter, const Vec3& initial_linear_momentum, const double total_mass, const std::uint64_t baseline_steps_simulated) {
    const double elapsed_seconds = (static_cast<double>(config::steps_simulated.load()) - static_cast<double>(baseline_steps_simulated)) * runtime_config::time_step;
    return baseline_barycenter + initial_linear_momentum / total_mass * elapsed_seconds;
}

void simulation::reset_diagnostics_baseline() {
    const double total_mass = calculate_total_mass();
    diagnostics_baseline = {
        .total_energy    = calculate_total_energy(),
        .linear_momentum = calculate_linear_momentum(),
        .barycenter      = std::isfinite(total_mass) && total_mass != 0.0 ? calculate_barycenter(total_mass) : Vec3{},
        .steps_simulated = config::steps_simulated.load()
    };
}


GraphSample simulation::make_graph_sample() {
    GraphSample sample;
    sample.step = config::steps_simulated.load();

    if (!accelerations_at_current_positions) {
        // The next simulate_step reuses this cache, so this costs no extra force evaluation
        accelerations_at_current_positions = compute_accelerations();
    }

    const auto& accelerations = *accelerations_at_current_positions;

    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        if (celestial_bodies.enabled[i]) {
            sample.body_id[i] = celestial_bodies.body_ids[i]; // enabled

            sample.position[i] = celestial_bodies.position(i);
            sample.velocity[i] = celestial_bodies.velocity(i);
            sample.mass[i] = celestial_bodies.gravitational_masses[i] / config::GRAVITATIONAL_CONSTANT;
            sample.acceleration[i] = {accelerations.x[i], accelerations.y[i], accelerations.z[i]};
        } else {
            sample.body_id[i] = config::NO_BODY_ID; // disabled

            // Disabled bodies keep NaN values
            constexpr double NaN = std::numeric_limits<double>::quiet_NaN();
            sample.position[i] = sample.velocity[i] = sample.acceleration[i] = {NaN, NaN, NaN};
            sample.mass[i] = NaN;
        }
    }

    sample.energy = calculate_total_energy();
    sample.energy_drift = sample.energy - diagnostics_baseline.total_energy;
    sample.kinetic_energy = calculate_kinetic_energy();

    sample.momentum = calculate_linear_momentum();
    sample.momentum_drift = sample.momentum - diagnostics_baseline.linear_momentum;

    const double total_mass = calculate_total_mass();

    if (std::isfinite(total_mass) && total_mass != 0.0) {
        const Vec3 barycenter = calculate_barycenter(total_mass);
        const Vec3 expected = calculate_expected_barycenter(
            diagnostics_baseline.barycenter,
            diagnostics_baseline.linear_momentum,
            total_mass,
            diagnostics_baseline.steps_simulated
        );

        sample.barycenter_drift = barycenter - expected;
        sample.barycenter_valid = std::isfinite(sample.barycenter_drift.x)
                                  && std::isfinite(sample.barycenter_drift.y)
                                  && std::isfinite(sample.barycenter_drift.z);
    }

    sample.hierarchy = compute_hierarchy(current_point_masses());

    return sample;
}

void simulation::simulate_cpu(const std::stop_token& stop_token) {
    auto last_publish = std::chrono::steady_clock::now();
    double last_budget_seconds = config::timer.seconds(); // Only advances while running
    double step_budget = 0.0;
    std::size_t since_check = 0;

    auto publish_if_due = [&] {
        const auto now = std::chrono::steady_clock::now();
        // publish at 1.2x the target FPS (smoother)
        if (now - last_publish >= std::chrono::duration<double>(1.0 / (config::TARGET_FPS * 1.2))) {
            publish_snapshot();
            last_publish = now;
        }
    };

    while (!stop_token.stop_requested()) {
        // If the **animation** appears laggy / slow, try lowering this
        // It does not affect CPU simulation speed
        constexpr step_t MAX_STEPS_PER_BATCH = 4096;
        constexpr double MAX_CATCH_UP_SECONDS = 0.25;

        CommandBatch batch;

        while (!batch.stop) {
            const auto cmd = ui_data::simulation_command_queue.try_pop();
            if (!cmd) break;
            std::visit([&](const auto& c) {
                batch.apply(c);
            }, *cmd);
        }

        if (batch.restored_checkpoint) {
            step_budget = 0.0;
            since_check = 0;
            last_budget_seconds = config::timer.seconds();
        }

        if (batch.physical_edit || batch.restored_checkpoint) {
            reset_diagnostics_baseline();
        }

        if (batch.bodies_changed) {
            accelerations_at_current_positions.reset(); // Reset stale accelerations

            // If a position "jump" happened: Clear all orbit trails
            if constexpr (config::CLEAR_ORBITS_AFTER_POSITION_EDIT) {
                if (batch.position_jump) {
                    clear_orbit_histories();
                }
            }

            // Publish
            config::republish_needed = false;
            publish_snapshot();
            last_publish = std::chrono::steady_clock::now();
        }

        // Delete graph history
        if (batch.restored_checkpoint || batch.clear_graphs) graph_history.clear();

        // Record a new sample
        if ((batch.physical_edit || batch.restored_checkpoint || batch.clear_graphs) && !runtime_config::headless) {
            auto sample = make_graph_sample();
            sample.starts_segment = batch.physical_edit && !batch.restored_checkpoint && !batch.clear_graphs;
            graph_history.record(sample);
        }

        if (batch.checkpoints_changed) {
            // Publish
            config::republish_needed = false;
            publish_snapshot();
            last_publish = std::chrono::steady_clock::now();
        }

        if (!config::timer.is_running()) {
            step_budget = 0.0;
            last_budget_seconds = config::timer.seconds();


            if (batch.requested_steps) {
                const step_t current = config::steps_simulated.load();

                const step_t remaining = runtime_config::target_steps
                                             ? (current < *runtime_config::target_steps
                                                    ? *runtime_config::target_steps - current
                                                    : 0)
                                             : *batch.requested_steps;

                const step_t steps_to_simulate = std::min(remaining, *batch.requested_steps);

                ui_data::set_step_progress({
                    .busy      = true,
                    .completed = 0,
                    .total     = steps_to_simulate
                });

                std::size_t completed = 0;

                config::timer.resume();

                while (completed < steps_to_simulate && !stop_token.stop_requested()) {
                    simulate_step();
                    completed++;

                    if (completed % MAX_STEPS_PER_BATCH == 0) {
                        ui_data::set_step_progress({
                            .busy      = true,
                            .completed = completed,
                            .total     = steps_to_simulate
                        });

                        publish_if_due();
                    }
                }

                config::timer.pause();

                ui_data::set_step_progress({
                    .busy      = true,
                    .completed = completed,
                    .total     = steps_to_simulate
                });

                config::republish_needed = true;
            }

            if (config::republish_needed) {
                config::republish_needed = false;
                publish_snapshot();
                last_publish = std::chrono::steady_clock::now();
            }

            if (batch.requested_steps) {
                since_check = 0;
                last_budget_seconds = config::timer.seconds();

                ui_data::set_step_progress({});
            }

            std::this_thread::sleep_for(std::chrono::milliseconds(1000 / config::TARGET_FPS));
            continue;
        }

        if (runtime_config::target_steps.has_value()
            && config::steps_simulated.load() >= *runtime_config::target_steps) {
            config::timer.pause();
            publish_snapshot();
            last_publish = std::chrono::steady_clock::now();
            continue;
        }

        const double speed = runtime_config::target_simulation_speed.load(std::memory_order_relaxed);
        const double steps_per_second = speed * config::SECONDS_PER_YEAR / runtime_config::time_step;

        if (speed <= 0.0) {
            simulate_step();

            if (++since_check >= MAX_STEPS_PER_BATCH) {
                since_check = 0;
                publish_if_due();
            }

            continue;
        }

        const double timer_seconds = config::timer.seconds();
        const double elapsed = std::max(0.0, timer_seconds - last_budget_seconds); // Clamped in case the timer is ever set back
        last_budget_seconds = timer_seconds;

        double max_budget = std::max(
            1.0,
            steps_per_second * MAX_CATCH_UP_SECONDS
        );

        step_budget = std::min(
            step_budget + elapsed * steps_per_second,
            max_budget
        );

        const auto steps_to_run = static_cast<std::size_t>(std::min(step_budget, static_cast<double>(MAX_STEPS_PER_BATCH)));

        if (steps_to_run == 0) {
            const double seconds_to_next_step = (1.0 - step_budget) / steps_per_second;

            std::this_thread::sleep_for(std::chrono::duration<double>(
                std::min(seconds_to_next_step, 1.0 / config::TARGET_FPS)
            ));
            continue;
        }

        for (std::size_t i = 0; i < steps_to_run; ++i) {
            simulate_step();
        }

        step_budget -= static_cast<double>(steps_to_run);
        publish_if_due();
    }
}

bool simulation::finalize_csv_output() {
    if (!csv_output_initialized) return true;

    bool write_succeeded = record_csv_sample(true);

    if (runtime_config::csv_live) {
        if (live_csv_file.is_open()) {
            live_csv_file.close();
            if (!live_csv_file && !live_csv_write_failed) {
                std::cerr << "Error: Failed to finish writing CSV data to "
                    << *runtime_config::csv_path << ".\n";
                write_succeeded = false;
            }
        }

        csv_output_initialized = false;
        return write_succeeded && !live_csv_write_failed;
    }

    std::ofstream csv_file(*runtime_config::csv_path, std::ios::out | std::ios::trunc);
    if (!csv_file.is_open()) {
        std::cerr << "Error: Could not open CSV file " << *runtime_config::csv_path << ".\n";
        csv_output_initialized = false;
        return false;
    }

    // Preserve enough digits to reconstruct the original double values.
    csv_file.precision(std::numeric_limits<double>::max_digits10);
    write_csv_header(csv_file);
    for (const auto& entry : csv_data) {
        write_csv_entry(csv_file, entry);
    }

    csv_file.close();
    if (!csv_file) {
        std::cerr << "Error: Failed to write CSV data to " << *runtime_config::csv_path << ".\n";
        write_succeeded = false;
    }

    csv_output_initialized = false;
    return write_succeeded;
}

void simulation::print_final_state() {
    const double seconds = config::timer.seconds();

    std::cout << std::format("Simulated years per second: {:.9f}\n", seconds > 0.0 ? ui_helpers::simulated_years() / seconds : 0);
    std::cout << std::format("Computation time: {:.9f} seconds\n", seconds);
    std::cout << std::format("Simulation time: {:.9f} years (@ 365 days)\n", ui_helpers::simulated_years());

    std::cout << std::format("Interaction set: {}\n", runtime_config::interaction_set_name());
    std::cout << std::format("Active force pairs: {}\n", force_pairs::active_pair_count());
    std::cout << std::format("Skipped force pairs: {}\n", force_pairs::skipped_pair_count());
    std::cout << std::format("SIMD: {}\n", runtime_config::use_simd);

    std::cout << std::format("Acceleration evaluations: {}\n", force_pairs::acceleration_evaluation_count());
    std::cout << std::format("Newtonian pair evaluations: {}\n", force_pairs::pair_evaluation_count());

    std::cout << std::format("Steps simulated: {}\n", config::steps_simulated.load());
    std::cout << std::format("Time step: {} seconds\n", runtime_config::time_step);
    std::cout << std::format("Body set: {}\n", runtime_config::body_set_name());
    std::cout << std::format("Invocation command: {}\n", runtime_config::invocation_command);

    std::cout << "Enabled body indices: ";
    bool first_enabled_body = true;
    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;
        if (!first_enabled_body) std::cout << ',';
        std::cout << i;
        first_enabled_body = false;
    }
    std::cout << '\n';

    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        std::cout << celestial_bodies.position(i).to_exact_string();
        if (i != NUM_CELESTIAL_BODIES - 1) {
            std::cout << '|';
        }
    }
    std::cout << '\n';
}
