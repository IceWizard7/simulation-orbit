    // Ancestor just below a root (ex. Earth for the Moon, Earth for Earth); roots return themselves
    [[nodiscard]] std::size_t local_system_root(const Hierarchy& h, std::size_t i) {
        // Terminates: every host is strictly heavier, so the chain can't loop
        while (h.host[i] && h.host[*h.host[i]]) i = *h.host[i];
        return i;
    }

    // Same planet-level system right now (planet + its moons, sibling moons), from the dynamic hierarchy Roots (ex. the Sun) belong to no local system
    [[nodiscard]] bool share_local_system(const Hierarchy& h, const std::size_t a, const std::size_t b) {
        return h.host[a] && h.host[b] && local_system_root(h, a) == local_system_root(h, b);
    }

    // Interpolates a timestamped history at non-decreasing steps in amortized O(1)
    // Linear between neighboring samples; past the newest sample it continues linearly to `head` (the current position at `head_step`)
    // nullopt outside the covered range
    class HistoryCursor {
        const std::deque<OrbitSample>& history;
        step_t head_step;
        Vec3 head;
        std::size_t k = 0; // history[k].step <= step of the last query

    public:
        HistoryCursor(const std::deque<OrbitSample>& history, const step_t head_step, const Vec3& head)
        : history(history), head_step(head_step), head(head) {
        }

        [[nodiscard]] std::optional<Vec3> at(const step_t step) {
            if (history.empty() || step < history.front().step || step > head_step) return std::nullopt;

            const OrbitSample& newest = history.back();
            if (step >= newest.step) {
                if (head_step == newest.step) return newest.position;
                const double t = static_cast<double>(step - newest.step) / static_cast<double>(head_step - newest.step);
                return newest.position + (head - newest.position) * t;
            }

            // step < newest.step, so history[k + 1] stays in range
            while (history[k + 1].step < step) k++;

            const OrbitSample& a = history[k];
            const OrbitSample& b = history[k + 1];
            if (b.step == step) return b.position;
            const double t = static_cast<double>(step - a.step) / static_cast<double>(b.step - a.step);
            return a.position + (b.position - a.position) * t;
        }
    };

    // Walks a history's steps in increasing order; calls f(step) for every sample with lo < step < hi
    class StepWalker {
        const std::deque<OrbitSample>& history;
        std::size_t k = 0;

    public:
        explicit StepWalker(const std::deque<OrbitSample>& history) : history(history) {
        }

        void for_each_between(const std::size_t lo, const std::size_t hi, auto&& f) {
            while (k < history.size() && history[k].step <= lo) k++;
            while (k < history.size() && history[k].step < hi) f(history[k++].step);
        }
    };

    std::array<std::optional<PointMass>, NUM_CELESTIAL_BODIES> current_point_masses() {
        std::array<std::optional<PointMass>, NUM_CELESTIAL_BODIES> result;

        for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
            if (simulation::celestial_bodies.enabled[i]) {
                result[i] = PointMass{
                    simulation::celestial_bodies.position(i),
                    simulation::celestial_bodies.velocity(i),
                    simulation::celestial_bodies.gravitational_masses[i] / config::GRAVITATIONAL_CONSTANT
                };
            }
        }

        return result;
    }

    struct CommandBatch {
        bool bodies_changed = false;
        bool physical_edit = false;
        bool position_jump = false; // Only teleports break trails; mass/velocity/create/delete keep continuous history
        bool restored_checkpoint = false;
        bool checkpoints_changed = false;
        bool clear_graphs = false;
        std::optional<step_t> requested_steps;
        bool stop = false; // StepN: stop processing further commands in this batch

        void apply(const ui_data::UpdateBodyCommand& cmd) {
            const auto valid = [](const std::optional<double>& value) {
                return !value || std::isfinite(*value);
            };

            if (cmd.i >= NUM_CELESTIAL_BODIES) return;

            if (cmd.reference_index) {
                if (*cmd.reference_index >= NUM_CELESTIAL_BODIES || *cmd.reference_index == cmd.i || !simulation::celestial_bodies.enabled[*cmd.reference_index]) {
                    return;
                }
            }

            ui_data::UpdateBodyCommand absolute = cmd;

            if (cmd.reference_index) {
                const Vec3 position = simulation::celestial_bodies.position(*cmd.reference_index);
                const Vec3 velocity = simulation::celestial_bodies.velocity(*cmd.reference_index);

                if (absolute.px) *absolute.px += position.x;
                if (absolute.py) *absolute.py += position.y;
                if (absolute.pz) *absolute.pz += position.z;

                if (absolute.vx) *absolute.vx += velocity.x;
                if (absolute.vy) *absolute.vy += velocity.y;
                if (absolute.vz) *absolute.vz += velocity.z;
            }


            if (!valid(absolute.mass) ||
                !valid(absolute.px) || !valid(absolute.py) || !valid(absolute.pz) ||
                !valid(absolute.vx) || !valid(absolute.vy) || !valid(absolute.vz) ||
                !valid(cmd.physical_radius_m) || (cmd.physical_radius_m && *cmd.physical_radius_m < 0.0) ||
                (cmd.name && is_blank(*cmd.name))) {
                return;
            }

            bodies_changed = true;
            position_jump |= cmd.px || cmd.py || cmd.pz;
            physical_edit |= cmd.mass || cmd.px || cmd.py || cmd.pz || cmd.vx || cmd.vy || cmd.vz;

            if (cmd.mass) simulation::celestial_bodies.gravitational_masses[cmd.i] = *cmd.mass * config::GRAVITATIONAL_CONSTANT;
            if (absolute.px) simulation::celestial_bodies.pos_x[cmd.i] = *absolute.px;
            if (absolute.py) simulation::celestial_bodies.pos_y[cmd.i] = *absolute.py;
            if (absolute.pz) simulation::celestial_bodies.pos_z[cmd.i] = *absolute.pz;
            if (absolute.vx) simulation::celestial_bodies.vel_x[cmd.i] = *absolute.vx;
            if (absolute.vy) simulation::celestial_bodies.vel_y[cmd.i] = *absolute.vy;
            if (absolute.vz) simulation::celestial_bodies.vel_z[cmd.i] = *absolute.vz;
            if (cmd.disable_rendering) simulation::celestial_bodies.rendering_visible[cmd.i] = false;
            if (cmd.enable_rendering) simulation::celestial_bodies.rendering_visible[cmd.i] = true;
            if (cmd.name) simulation::celestial_bodies.names[cmd.i] = *cmd.name;
            if (cmd.physical_radius_m) simulation::celestial_bodies.physical_radius_m[cmd.i] = *cmd.physical_radius_m;
            if (cmd.color) simulation::celestial_bodies.colors[cmd.i] = *cmd.color;
            if (cmd.clear_texture) simulation::celestial_bodies.texture_ids[cmd.i].reset();
            else if (cmd.texture_id) simulation::celestial_bodies.texture_ids[cmd.i] = cmd.texture_id;
        }

        void apply(const ui_data::CaptureCheckpoint&) {
            checkpoints_changed = true;
            simulation::save_checkpoint();
        }

        void apply(const ui_data::RestoreCheckpoint& cmd) {
            if (simulation::load_checkpoint(cmd.id)) {
                checkpoints_changed = true;
                restored_checkpoint = true;
            }
        }

        void apply(const ui_data::ImportStateCommand& cmd) {
            if (simulation::import_state(cmd)) {
                checkpoints_changed = true;
                restored_checkpoint = true; // Same follow-up as a restore: baselines, graph history, pause, publish
            }
        }

        void apply(const ui_data::DeleteCheckpoint& cmd) {
            checkpoints_changed |= simulation::delete_checkpoint(cmd.id);
        }

        void apply(const ui_data::RenameCheckpoint& cmd) {
            checkpoints_changed |= simulation::rename_checkpoint(cmd.id, cmd.new_label);
        }


        void apply(const ui_data::StepN& cmd) {
            if (!config::timer.is_running() && cmd.n > 0) {
                requested_steps = cmd.n;
            } else {
                ui_data::set_step_progress({});
            }

            // Because the queue is FIFO, after processing a step command (which happens here), we stop processing
            // all other commands until the step happened
            stop = true;
        }

        void apply(const ui_data::ClearGraphs&) {
            clear_graphs = true;
        }

        void apply(const ui_data::CreateBodyCommand& cmd) {
            if (simulation::create_body(cmd)) {
                bodies_changed = true;
                physical_edit = true;
            }
        }

        void apply(const ui_data::DeleteBodyCommand& cmd) {
            if (simulation::delete_body(cmd.i)) {
                bodies_changed = true;
                physical_edit = true;
            }
        }
    };
