void simulation::apply_planet_systems_approximation() {
    for (const auto& [parent_index, moon_indices] : planetary_systems) {
        double total_gravitational_mass = celestial_bodies.original_gravitational_masses[parent_index];
        Vec3 weighted_position = celestial_bodies.position(parent_index) * celestial_bodies.original_gravitational_masses[parent_index];
        Vec3 weighted_velocity = celestial_bodies.velocity(parent_index) * celestial_bodies.original_gravitational_masses[parent_index];

        for (const std::size_t moon_index : moon_indices) {
            total_gravitational_mass += celestial_bodies.original_gravitational_masses[moon_index];
            weighted_position += celestial_bodies.position(moon_index) * celestial_bodies.original_gravitational_masses[moon_index];
            weighted_velocity += celestial_bodies.velocity(moon_index) * celestial_bodies.original_gravitational_masses[moon_index];
            celestial_bodies.enabled[moon_index] = false;
        }

        celestial_bodies.set_position(parent_index, weighted_position / total_gravitational_mass);
        celestial_bodies.set_velocity(parent_index, weighted_velocity / total_gravitational_mass);
        celestial_bodies.gravitational_masses[parent_index] = total_gravitational_mass;
    }

    accelerations_at_current_positions.reset();
}

std::ofstream simulation::live_csv_file;
std::optional<step_t> simulation::last_csv_sample_step;
bool simulation::csv_output_initialized = false;
bool simulation::live_csv_write_failed = false;

CSVEntry simulation::capture_csv_entry() {
    CSVEntry entry;
    entry.step = config::steps_simulated.load();
    entry.simulated_seconds = entry.step * static_cast<std::size_t>(runtime_config::time_step);

    for (std::size_t i = 0; i < NUM_CATALOG_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;
        entry.positions[i] = celestial_bodies.position(i);
        entry.velocities[i] = celestial_bodies.velocity(i);
    }

    return entry;
}

void simulation::write_csv_header(std::ostream& output) {
    output << "step,";
    output << "simulated_seconds";
    for (std::size_t i = 0; i < NUM_CATALOG_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;
        output << ',' << celestial_bodies.names[i] << "_position_x"
            << ',' << celestial_bodies.names[i] << "_position_y"
            << ',' << celestial_bodies.names[i] << "_position_z"
            << ',' << celestial_bodies.names[i] << "_velocity_x"
            << ',' << celestial_bodies.names[i] << "_velocity_y"
            << ',' << celestial_bodies.names[i] << "_velocity_z";
    }
    output << '\n';
}

void simulation::write_csv_entry(std::ostream& output, const CSVEntry& entry) {
    output << entry.step << "," << entry.simulated_seconds;

    for (std::size_t i = 0; i < NUM_CATALOG_BODIES; i++) {
        const auto& position = entry.positions[i];
        const auto& velocity = entry.velocities[i];

        if (!position.has_value()) continue;
        if (!velocity.has_value()) continue;

        output << ',' << position->x
            << ',' << position->y
            << ',' << position->z
            << ',' << velocity->x
            << ',' << velocity->y
            << ',' << velocity->z;
    }

    output << '\n';
}

bool simulation::report_live_csv_write_failure(const step_t step) {
    if (!live_csv_write_failed) {
        std::cerr << "Error: Failed to write CSV sample at step " << step
            << " to " << *runtime_config::csv_path << ".\n";
        live_csv_write_failed = true;
    }
    return false;
}

bool simulation::record_csv_sample(const bool force) {
    if (!csv_output_initialized || !runtime_config::csv_path.has_value()) return true;
    if (live_csv_write_failed) return false;

    const step_t step = config::steps_simulated.load();
    if (last_csv_sample_step.has_value() && *last_csv_sample_step == step) return true;

    if (!force) {
        if (!runtime_config::sample_csv_data_every_steps.has_value()) return true;

        const step_t cadence = *runtime_config::sample_csv_data_every_steps;
        if (cadence == 0 || step % cadence != 0) return true;
    }

    const CSVEntry entry = capture_csv_entry();
    if (runtime_config::csv_live) {
        write_csv_entry(live_csv_file, entry);
        live_csv_file.flush();
        if (!live_csv_file) return report_live_csv_write_failure(step);
    } else {
        csv_data.push_back(entry);
    }

    last_csv_sample_step = step;
    return true;
}

void simulation::initialize_orbit_sampling() {
    orbit_max_gap_steps = std::max<std::size_t>(
        1,
        static_cast<std::size_t>(config::ORBIT_MAX_SAMPLE_GAP_SECONDS / runtime_config::time_step)
    );

    constexpr double center_reference_seconds_per_point_target =
        config::SECONDS_PER_YEAR / config::ORBIT_CENTER_REFERENCE_POINTS_PER_YEAR;
    orbit_center_reference_sample_every_steps = std::max<std::size_t>(
        1,
        static_cast<std::size_t>(center_reference_seconds_per_point_target / runtime_config::time_step)
    );

    const double center_reference_seconds_per_point =
        static_cast<double>(orbit_center_reference_sample_every_steps) * runtime_config::time_step;
    orbit_center_reference_max_points = std::max<std::size_t>(
        2,
        static_cast<std::size_t>(std::ceil(
            config::ORBIT_CENTER_REFERENCE_YEARS * config::SECONDS_PER_YEAR / center_reference_seconds_per_point
        )) + 1
    );

    // Hosts for the turning-angle sampling until the first publication refreshes them
    orbit_sampling_host = compute_hierarchy(current_point_masses()).host;

    // Seed every history with the step-0 state so all bodies' coverage starts together
    save_orbit_points();
}

void simulation::clear_orbit_histories() {
    for (auto& history : orbit_history) history.clear();
    for (auto& history : orbit_center_reference_history) history.clear();
    orbit_turn_since_sample.fill(0.0);
}

void simulation::clear_orbit_history(const std::size_t i) {
    orbit_history[i].clear();
    orbit_center_reference_history[i].clear();
    orbit_turn_since_sample[i] = 0.0;
}

std::optional<std::size_t> simulation::create_body(const ui_data::CreateBodyCommand& cmd) {
    // Don't allow SIMD / non-full interation sets
    if (runtime_config::use_simd || runtime_config::interaction_set != runtime_config::InteractionSet::full) return std::nullopt;

    // Compute absolut position & velocity (changes if reference was set)
    Vec3 position = cmd.position;
    Vec3 velocity = cmd.velocity;

    if (cmd.reference_index) {
        const std::size_t r = *cmd.reference_index;
        if (r >= NUM_CELESTIAL_BODIES || !celestial_bodies.enabled[r]) return std::nullopt;
        position += celestial_bodies.position(r);
        velocity += celestial_bodies.velocity(r);
    }

    // Finite values (zero/negative masses stay allowed, like edits)
    const auto finite = [](const Vec3& value) {
        return std::isfinite(value.x) && std::isfinite(value.y) && std::isfinite(value.z);
    };

    // Finite: position, velocity, mass, physical_radius_m
    // physical_radius_m must be >= 0
    if (!finite(position) || !finite(velocity) || !std::isfinite(cmd.mass)
        || !std::isfinite(cmd.physical_radius_m) || cmd.physical_radius_m < 0
        || is_blank(cmd.name)) {
        return std::nullopt;
    }

    // Free slot for the new (custom) body
    std::optional<std::size_t> slot;

    // Custom bodies live only in the custom range: slot < NUM_CATALOG_BODIES always means "this is a catalog body"
    for (std::size_t i = NUM_CATALOG_BODIES; i < NUM_CELESTIAL_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) {
            slot = i;
            break;
        }
    }

    if (!slot) return std::nullopt;
    const std::size_t i = *slot;

    // Overwrite every field (the slot may contain a deleted body's leftovers)
    celestial_bodies.set_position(i, position);
    celestial_bodies.set_velocity(i, velocity);

    celestial_bodies.physical_radius_m[i] = cmd.physical_radius_m;

    celestial_bodies.enabled[i] = true;
    celestial_bodies.rendering_visible[i] = true;

    const double gravitational_mass = cmd.mass * config::GRAVITATIONAL_CONSTANT;
    celestial_bodies.original_gravitational_masses[i] = gravitational_mass;
    celestial_bodies.gravitational_masses[i] = gravitational_mass;

    celestial_bodies.names[i] = cmd.name;

    celestial_bodies.draw_radii_2d[i] = config::CUSTOM_BODY_RADIUS_2D;
    celestial_bodies.draw_radii_3d[i] = config::CUSTOM_BODY_RADIUS_3D;

    celestial_bodies.colors[i] = cmd.color;

    celestial_bodies.texture_ids[i] = cmd.texture_id;

    celestial_bodies.j2[i] = 0.0;
    celestial_bodies.equatorial_radii[i] = 0.0;
    celestial_bodies.pole_axes[i] = Vec3{};

    celestial_bodies.body_ids[i] = celestial_bodies.next_body_id++;

    // Slot-specific state
    clear_orbit_history(i);
    graph_history.invalidate_body(i);

    // Rebuild the pairs
    force_pairs::initialize_all_pairs(celestial_bodies);
    force_pairs::set_interaction_set(planetary_systems);

    return i;
}

bool simulation::delete_body(const std::size_t i) {
    // Don't allow SIMD / non-full interation sets
    if (runtime_config::use_simd || runtime_config::interaction_set != runtime_config::InteractionSet::full) return false;

    if (i >= NUM_CELESTIAL_BODIES || !celestial_bodies.enabled[i]) return false;

    // Deleting the last body is allowed: An empty simulation can be the starting point for a custom scenario

    celestial_bodies.enabled[i] = false;
    clear_orbit_history(i);

    // The coordinate origin must not stay on a (frozen) deleted body
    if (config::center_celestial_body_index.load() == i) {
        config::center_celestial_body_index = config::NO_BODY_SELECTED;
    }

    // Rebuild the pairs
    force_pairs::initialize_all_pairs(celestial_bodies);
    force_pairs::set_interaction_set(planetary_systems);

    return true;
}

void simulation::save_orbit_points() {
    // Trails are rendering-only; headless runs never draw them
    if (runtime_config::headless) return;

    const step_t step = config::steps_simulated.load();

    // Velocity-direction turn per primary sample (1024 samples per circular orbit)
    constexpr double TURN_PER_SAMPLE = 2.0 * std::numbers::pi / config::ORBIT_POINTS_PER_REVOLUTION;

    // Endpoint accelerations of the step that just finished (absent at step 0 and after edits/restores)
    const Accelerations* acc = accelerations_at_current_positions ? &*accelerations_at_current_positions : nullptr;

    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;

        if (step % orbit_center_reference_sample_every_steps == 0) {
            auto& center_reference_history = orbit_center_reference_history[i];
            center_reference_history.push_back({step, celestial_bodies.position(i)});

            if (center_reference_history.size() > orbit_center_reference_max_points) {
                center_reference_history.pop_front();
            }
        }

        if (acc) {
            // Turning rate of the velocity direction: ω = |v × a| / |v|² (circular orbit: ω = 2π/T)
            // Relative to the host: the Moon's inertial path is almost Earth's and barely curves
            Vec3 v = celestial_bodies.velocity(i);
            Vec3 a{acc->x[i], acc->y[i], acc->z[i]};

            if (const auto host = orbit_sampling_host[i]; host && celestial_bodies.enabled[*host]) {
                v -= celestial_bodies.velocity(*host);
                a -= Vec3{acc->x[*host], acc->y[*host], acc->z[*host]};
            }

            const double v_squared = v.dot(v);
            const double turn = v.cross(a).length() / v_squared * runtime_config::time_step;
            if (v_squared > 0.0 && std::isfinite(turn)) orbit_turn_since_sample[i] += turn;
        }

        auto& history = orbit_history[i];

        const bool due = history.empty()
                         || orbit_turn_since_sample[i] >= TURN_PER_SAMPLE
                         || step - history.back().step >= orbit_max_gap_steps;
        if (!due) continue;

        history.push_back({step, celestial_bodies.position(i)});
        orbit_turn_since_sample[i] = 0.0;

        if (history.size() > config::ORBIT_MAX_POINTS) {
            history.pop_front();
        }
    }
}

bool simulation::initialize_csv_output() {
    csv_data.clear();
    last_csv_sample_step.reset();
    live_csv_write_failed = false;
    csv_output_initialized = false;

    const bool has_path = runtime_config::csv_path.has_value();
    const bool has_cadence = runtime_config::sample_csv_data_every_steps.has_value();
    if (!has_path && !has_cadence && !runtime_config::csv_live) return true;

    if (!has_path || !has_cadence || *runtime_config::sample_csv_data_every_steps == 0) {
        std::cerr << "Error: CSV output requires a path and a positive sampling cadence.\n";
        return false;
    }

    if (runtime_config::csv_live) {
        live_csv_file.open(*runtime_config::csv_path, std::ios::out | std::ios::trunc);
        if (!live_csv_file.is_open()) {
            std::cerr << "Error: Could not open CSV file " << *runtime_config::csv_path << ".\n";
            return false;
        }

        live_csv_file.precision(std::numeric_limits<double>::max_digits10);
        write_csv_header(live_csv_file);
        if (!live_csv_file) {
            std::cerr << "Error: Failed to write CSV header to " << *runtime_config::csv_path << ".\n";
            live_csv_write_failed = true;
            live_csv_file.close();
            return false;
        }
    }

    csv_output_initialized = true;
    if (record_csv_sample(true)) return true;

    if (live_csv_file.is_open()) live_csv_file.close();
    csv_output_initialized = false;
    return false;
}

void simulation::update_csv_data() {
    record_csv_sample(false);
}

#if defined(__aarch64__) && defined(__ARM_NEON)
namespace {
    Accelerations compute_accelerations_full_neon() {
        const auto& bodies = simulation::celestial_bodies;
        Accelerations a{};

        const auto one = vdupq_n_f64(1.0);

        for (std::size_t i = 0; i < NUM_CATALOG_BODIES; ++i) {
            // Copy values into both lanes
            const auto xi = vdupq_n_f64(bodies.pos_x[i]);
            const auto yi = vdupq_n_f64(bodies.pos_y[i]);
            const auto zi = vdupq_n_f64(bodies.pos_z[i]);
            const auto gm_i = vdupq_n_f64(bodies.gravitational_masses[i]);

            // Creates 3 SIMD accumulators
            auto sum_x = vdupq_n_f64(0.0);
            auto sum_y = vdupq_n_f64(0.0);
            auto sum_z = vdupq_n_f64(0.0);

            std::size_t j = i + 1;

            for (; j + 1 < NUM_CATALOG_BODIES; j += 2) {
                // Lane 0: Pair (i, j), Lane 1: Pair (i, j+1)
                const auto dx = vsubq_f64(vld1q_f64(bodies.pos_x + j), xi);
                const auto dy = vsubq_f64(vld1q_f64(bodies.pos_y + j), yi);
                const auto dz = vsubq_f64(vld1q_f64(bodies.pos_z + j), zi);

                const auto r2 = vaddq_f64(
                    vaddq_f64(vmulq_f64(dx, dx), vmulq_f64(dy, dy)),
                    vmulq_f64(dz, dz)
                );

                const auto inv_r3 = vdivq_f64(
                    one,
                    vmulq_f64(r2, vsqrtq_f64(r2))
                );

                const auto factor_i = vmulq_f64(
                    vld1q_f64(bodies.gravitational_masses + j), inv_r3
                );
                const auto factor_j = vmulq_f64(gm_i, inv_r3);

                auto update_axis = [&](double* accelerations,
                                       const float64x2_t delta,
                                       float64x2_t& sum_i) {
                    sum_i = vaddq_f64(sum_i, vmulq_f64(delta, factor_i));

                    // Retroactive effect on j and j + 1
                    vst1q_f64(
                        accelerations + j,
                        vsubq_f64(
                            vld1q_f64(accelerations + j),
                            vmulq_f64(delta, factor_j)
                        )
                    );
                };

                update_axis(a.x, dx, sum_x);
                update_axis(a.y, dy, sum_y);
                update_axis(a.z, dz, sum_z);
            }

            // Add 2 lanes together
            a.x[i] += vaddvq_f64(sum_x);
            a.y[i] += vaddvq_f64(sum_y);
            a.z[i] += vaddvq_f64(sum_z);

            // If there are still indexes remaining
            if (j < NUM_CATALOG_BODIES) {
                const double dx = bodies.pos_x[j] - bodies.pos_x[i];
                const double dy = bodies.pos_y[j] - bodies.pos_y[i];
                const double dz = bodies.pos_z[j] - bodies.pos_z[i];

                const double r2 = dx * dx + dy * dy + dz * dz;
                const double inv_r3 = 1.0 / (r2 * std::sqrt(r2));

                const double factor_i = bodies.gravitational_masses[j] * inv_r3;
                const double factor_j = bodies.gravitational_masses[i] * inv_r3;

                a.x[i] += dx * factor_i;
                a.y[i] += dy * factor_i;
                a.z[i] += dz * factor_i;

                a.x[j] -= dx * factor_j;
                a.y[j] -= dy * factor_j;
                a.z[j] -= dz * factor_j;
            }
        }

        return a;
    }
}
#endif

Accelerations simulation::compute_accelerations() {
    force_pairs::record_acceleration_evaluation();

    if (runtime_config::use_simd) {
#if defined(__aarch64__)
        return compute_accelerations_full_neon();
#endif
    }

    Accelerations accelerations = {};

    for (const auto& [i, j] : force_pairs::active_pairs) {
        const Vec3 separation{
            celestial_bodies.pos_x[j] - celestial_bodies.pos_x[i],
            celestial_bodies.pos_y[j] - celestial_bodies.pos_y[i],
            celestial_bodies.pos_z[j] - celestial_bodies.pos_z[i]
        };
        const double distance = separation.length();
        const Vec3 first_to_second_direction = separation / distance;
        const double distance_squared = distance * distance;

        // Evaluate each Newtonian pair once
        // These accelerations correspond to equal-and-opposite forces because mass is proportional to GM
        accelerations.x[i] += first_to_second_direction.x * (celestial_bodies.gravitational_masses[j] / distance_squared);
        accelerations.y[i] += first_to_second_direction.y * (celestial_bodies.gravitational_masses[j] / distance_squared);
        accelerations.z[i] += first_to_second_direction.z * (celestial_bodies.gravitational_masses[j] / distance_squared);

        accelerations.x[j] -= first_to_second_direction.x * (celestial_bodies.gravitational_masses[i] / distance_squared);
        accelerations.y[j] -= first_to_second_direction.y * (celestial_bodies.gravitational_masses[i] / distance_squared);
        accelerations.z[j] -= first_to_second_direction.z * (celestial_bodies.gravitational_masses[i] / distance_squared);

        if (!runtime_config::use_j2) continue;

        // The direct J2 acceleration acts on the target
        // Its reaction on the oblate source is scaled by target_mass/source_mass, equivalently
        // target_GM/source_GM, so total linear momentum remains conserved
        if (celestial_bodies.j2[j] != 0.0 && celestial_bodies.gravitational_masses[j] != 0.0) {
            const Vec3 j2_on_first = celestial_bodies.j2_acceleration_at(
                j,
                first_to_second_direction * -1.0,
                distance
            );
            accelerations.x[i] += j2_on_first.x;
            accelerations.y[i] += j2_on_first.y;
            accelerations.z[i] += j2_on_first.z;

            accelerations.x[j] -= j2_on_first.x * (celestial_bodies.gravitational_masses[i] / celestial_bodies.gravitational_masses[j]);
            accelerations.y[j] -= j2_on_first.y * (celestial_bodies.gravitational_masses[i] / celestial_bodies.gravitational_masses[j]);
            accelerations.z[j] -= j2_on_first.z * (celestial_bodies.gravitational_masses[i] / celestial_bodies.gravitational_masses[j]);
        }

        if (celestial_bodies.j2[i] != 0.0 && celestial_bodies.gravitational_masses[i] != 0.0) {
            const Vec3 j2_on_second = celestial_bodies.j2_acceleration_at(
                i,
                first_to_second_direction,
                distance
            );
            accelerations.x[j] += j2_on_second.x;
            accelerations.y[j] += j2_on_second.y;
            accelerations.z[j] += j2_on_second.z;

            accelerations.x[i] -= j2_on_second.x * (celestial_bodies.gravitational_masses[j] / celestial_bodies.gravitational_masses[i]);
            accelerations.y[i] -= j2_on_second.y * (celestial_bodies.gravitational_masses[j] / celestial_bodies.gravitational_masses[i]);
            accelerations.z[i] -= j2_on_second.z * (celestial_bodies.gravitational_masses[j] / celestial_bodies.gravitational_masses[i]);
        }
    }

    return accelerations;
}

void simulation::simulate_step() {
    if (!accelerations_at_current_positions.has_value()) {
        accelerations_at_current_positions = compute_accelerations();
    }

    const auto& [acc_x, acc_y, acc_z] = *accelerations_at_current_positions;

    // Velocity Verlet: keep the orbit phase stable over many short-period inner-planet revolutions
    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;

        celestial_bodies.pos_x[i] += celestial_bodies.vel_x[i] * runtime_config::time_step + acc_x[i] * runtime_config::half_dt_squared;
        celestial_bodies.pos_y[i] += celestial_bodies.vel_y[i] * runtime_config::time_step + acc_y[i] * runtime_config::half_dt_squared;
        celestial_bodies.pos_z[i] += celestial_bodies.vel_z[i] * runtime_config::time_step + acc_z[i] * runtime_config::half_dt_squared;
    }

    const Accelerations next_accelerations = compute_accelerations();

    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;

        celestial_bodies.vel_x[i] += (acc_x[i] + next_accelerations.x[i]) * runtime_config::half_dt;
        celestial_bodies.vel_y[i] += (acc_y[i] + next_accelerations.y[i]) * runtime_config::half_dt;
        celestial_bodies.vel_z[i] += (acc_z[i] + next_accelerations.z[i]) * runtime_config::half_dt;
    }

    // accelerations_at_current_positions now correspond to next_accelerations
    accelerations_at_current_positions = next_accelerations;

    ++config::steps_simulated;
    save_orbit_points();
    update_csv_data();

    if (!runtime_config::headless && graph_history.due(config::steps_simulated)) {
        graph_history.record(make_graph_sample());
    }
}

// Builds a render snapshot from the simulation-owned state (no lock needed: the simulation thread is the only owner
// of celestial_bodies and both orbit histories) and publishes it atomically
void simulation::publish_snapshot() {
    auto snap = std::make_shared<ui_data::RenderSnapshot>();

    snap->center_index = config::center_celestial_body_index.load();
    const bool has_center_body = snap->center_index != config::NO_BODY_SELECTED;

    snap->step = config::steps_simulated.load();
    const Vec3 center = has_center_body ? celestial_bodies.position(snap->center_index) : Vec3{0, 0, 0};

    // Computed first: the trails below decide by it which center history they may use
    snap->hierarchy = compute_hierarchy(current_point_masses());
    orbit_sampling_host = snap->hierarchy.host;

    std::size_t max_used = 0;

    for (std::size_t i = 0; i < NUM_CELESTIAL_BODIES; i++) {
        if (!celestial_bodies.enabled[i]) continue;

        const Vec3 absolute_pos = celestial_bodies.position(i);
        const Vec3 relative_pos = absolute_pos - center;
        snap->bodies[i] = {
            .id                      = celestial_bodies.body_ids[i],
            .name                    = celestial_bodies.names[i],
            .relative_position       = relative_pos,
            .absolute_position       = absolute_pos,
            .velocity                = celestial_bodies.velocity(i),
            .mass                    = celestial_bodies.get_mass(i),
            .physical_radius_m       = celestial_bodies.physical_radius_m[i],
            .radius_2d               = celestial_bodies.draw_radii_2d[i],
            .radius_3d               = celestial_bodies.draw_radii_3d[i],
            .color                   = celestial_bodies.colors[i],
            .texture_id              = celestial_bodies.texture_ids[i],
            .rendering_visible       = celestial_bodies.rendering_visible[i],
            .gravitational_parameter = celestial_bodies.gravitational_masses[i],
            .j2                      = celestial_bodies.j2[i],
            .j2_reference_radius_m   = celestial_bodies.equatorial_radii[i],
            .pole_axis               = celestial_bodies.pole_axes[i],
        };

        const auto& history = orbit_history[i];
        max_used = std::max(max_used, history.size());

        // Don't include center in snapshot
        if (i == snap->center_index) continue;
        if (history.size() < 2) continue;

        snap->orbits[i].color = celestial_bodies.colors[i];

        auto& points = snap->orbits[i].points;
        const Vec3 body_now = celestial_bodies.position(i);

        if (!has_center_body) {
            points.reserve(history.size() + 1);
            for (const OrbitSample& sample : history) points.push_back(sample.position);
            points.push_back(body_now);
            continue;
        }

        const auto& center_history = orbit_history[snap->center_index];
        const auto& center_reference_history = orbit_center_reference_history[snap->center_index];

        // Bodies in the same planet-level system (planet + moons, siblings) need the center's high-resolution
        // history. Distant bodies may fall back to the coarse, centuries-long center history: its interpolation
        // error is invisible at planetary distances and allows complete outer orbits
        const bool allow_coarse = !share_local_system(snap->hierarchy, snap->center_index, i);
        const step_t fine_start = center_history.empty() ? snap->step : center_history.front().step;

        HistoryCursor body_at(history, snap->step, body_now);
        HistoryCursor center_fine_at(center_history, snap->step, center);
        // The coarse history only covers the past and ends at its newest sample
        HistoryCursor center_coarse_at(
            center_reference_history,
            center_reference_history.empty() ? 0 : center_reference_history.back().step,
            center_reference_history.empty() ? Vec3{} : center_reference_history.back().position
        );

        auto emit = [&](const step_t step) {
            const std::optional<Vec3> c = step >= fine_start
                                              ? center_fine_at.at(step)
                                              : allow_coarse
                                              ? center_coarse_at.at(step)
                                              : std::nullopt;
            if (!c) return; // outside the center's coverage

            if (const std::optional<Vec3> body = body_at.at(step)) points.push_back(*body - *c);
        };

        // The relative path contains the center's motion too: besides the body's own samples, emit points at
        // the center's samples in between (body interpolated linearly), or a slowly sampled body's trail in a
        // fast-moving frame becomes polygonal (ex. the Sun or Neptune with Earth as origin)
        // Steps stay increasing, as the cursors require
        StepWalker center_fine_steps(center_history);
        StepWalker center_coarse_steps(center_reference_history);
        points.reserve(history.size() + center_history.size() + 1);

        for (std::size_t j = 0; j < history.size(); j++) {
            const step_t lo = history[j].step;
            const step_t hi = j + 1 < history.size() ? history[j + 1].step : snap->step;

            emit(lo);
            if (allow_coarse && lo < fine_start) {
                center_coarse_steps.for_each_between(lo, std::min(hi, fine_start), emit);
            }
            center_fine_steps.for_each_between(lo, hi, emit);
        }

        // Connect the trail head to the body's current position
        if (history.back().step != snap->step) points.push_back(body_now - center);
    }

    snap->max_orbit_points_used = max_used;

    snap->checkpoints.reserve(checkpoints.size());

    for (const auto& checkpoint : checkpoints) {
        const double simulated_seconds = static_cast<double>(checkpoint.steps_simulated) * checkpoint.time_step;

        snap->checkpoints.push_back({checkpoint.id, simulated_seconds, checkpoint.label});
    }

    snap->linear_momentum = calculate_linear_momentum();
    snap->baseline_linear_momentum = diagnostics_baseline.linear_momentum;
    snap->momentum_drift = snap->linear_momentum - diagnostics_baseline.linear_momentum;

    snap->total_energy = calculate_total_energy();
    snap->baseline_energy = diagnostics_baseline.total_energy;
    snap->energy_drift = snap->total_energy - diagnostics_baseline.total_energy;

    const double total_mass = calculate_total_mass();

    if (std::isfinite(total_mass) && total_mass != 0.0) {
        snap->barycenter = calculate_barycenter(total_mass);
        snap->expected_barycenter = calculate_expected_barycenter(
            diagnostics_baseline.barycenter,
            snap->baseline_linear_momentum,
            total_mass,
            diagnostics_baseline.steps_simulated
        );

        snap->barycenter_drift = snap->barycenter - snap->expected_barycenter;
        const auto finite = [](const Vec3& value) {
            return std::isfinite(value.x) && std::isfinite(value.y) && std::isfinite(value.z);
        };
        snap->barycenter_valid = finite(snap->barycenter) && finite(snap->expected_barycenter) && finite(snap->barycenter_drift);
    }

    {
        std::lock_guard lock(config::snapshot_lock);
        config::latest_snapshot = std::move(snap);
    }
}

